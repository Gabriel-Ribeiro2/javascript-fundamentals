/*
Os operadores aritméticos são usados para realizar operações matemáticas em JavaScript
Eles são usados para realizar cálculos e manipular números.
Os operadores aritméticos mais comuns são:
+ (adição), - (subtração), * (multiplicação), / (divisão), % (módulo) e ** (exponenciação).
*/

// duas variáveis com valores numéricos
let num1 = 10;
let num2 = 5;

// adição
let sum = num1 + num2; // 10 + 5 = 15
console.log(sum);

// subtração
let subtraction = num1 - num2; // 10 - 5 = 5
console.log(subtraction);

// multiplicação
let multiplication = num1 * num2; // 10 * 5 = 50
console.log(multiplication);

// divisão
let division = num1 / num2; // 10 / 5 = 2
console.log(division);

// exponenciação
let exponentiation = num1 ** num2; // 10 ** 5 = 100000
console.log(exponentiation);

// módulo (resto da divisão)
let modulus = num1 % num2; // 10 / 5 = 0
console.log(modulus);
let modulus2 = 11 % 5; // 11 % 5 = 1
console.log(modulus2);
