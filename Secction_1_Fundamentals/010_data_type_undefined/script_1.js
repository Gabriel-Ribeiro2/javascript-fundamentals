//  Os tipos de dados 'null' e 'undefined' são os tipos de dados primitivos em JavaScript
// Que representam a ausência de valor ou a faltade definição de uma variável

let myNull = null;

console.log(myNull);

let myUndefined = undefined;

console.log(myUndefined);

// undefined significa que ainda não foi atribuido um valor à variável

let myNumber;

console.log(myNumber);

