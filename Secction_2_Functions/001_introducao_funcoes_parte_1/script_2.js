// definir uma função que recebe um parâmetro
function displayMessage(message) {
  console.log(message);
}

// chamar a função e passar um valor para o parâmetro
displayMessage("Hello World");
displayMessage("Goodbye World");

/*
Esta função recebe um parâmetro
O parâmetro é o valor que a função recebe para realizar uma tarefa
Podemos chamar a função quantas vezes quisermos
*/
