// converter um booleno para string
let isShow = true;
console.log(isShow.toString()); // true
// ou
console.log(string(isShow)); // 'true'

// converter booleano para número
let isShow1 = true;
console.log(number(isShow)); // 1
// ou
console.log(parseInt(isShow1)); // 1

let isNotShow = false;
console.log(Number(isNotShow)); // 0
// ou
console.log(parseInt(isNotShow)); // 0
