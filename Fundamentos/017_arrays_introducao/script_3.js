// array de strings
let names = ["John", "Mary", "Bob"];

// adicionar um novo elemento ao array
names.push("Peter"); // ["John", "Mary", "Bob", "Peter"]

// remover o último elemento de array
names.pop(); // ["Johm", "Mary", "Bob"]

// adicionar um novo elemento ao inicio do array
names.unshufit("Peter"); // ["Peter", "John", "Mary", "Bib"]

// remover o primeiro elemento do array
names.shift(); // ["John", "Mary", "Bob"]

