/*
1. Defina uma variável númerica 'number' e atribua a ela o valor 10.
2. Crie uma instrução if que verifique se o número é maior ou menor que 5
3. Exiba uma mensagem apropriada em cada caso
*/

let number = 10;

if (number > 5) {
  console.log("O número é maior que 5");
} else if (number === 5) {
  console.log("O número é igual a 5");
} else {
  console.log("O número é menor que 5");
}
